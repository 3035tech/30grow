#!/usr/bin/env node
/** Translate the ten first-party blog articles while preserving their structure. */
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { listBlogPosts } from '../lib/blog/index.js';
import { BLOG_CATEGORY_LABEL } from '../lib/blog/categories.js';
import { openAiChatCompletion, extractJsonObject, isOpenAiConfigured, isOpenAiMock } from '../lib/openai-chat.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'lib/blog/translations');
const TARGETS = {
  'pt-PT': 'European Portuguese (Portugal)',
  en: 'English (United States)',
  'es-419': 'Spanish (Latin America)',
  'es-ES': 'Spanish (Spain)',
  'fr-FR': 'French (France)',
  'de-DE': 'German (Germany)',
};

function sourceCopy(post) {
  return {
    title: post.title,
    description: post.description,
    keywords: post.keywords,
    categoryLabel: BLOG_CATEGORY_LABEL[post.category],
    intro: post.intro,
    sections: post.sections.map(({ heading, paragraphs, bullets }) => ({
      heading, paragraphs, ...(bullets ? { bullets } : {}),
    })),
    ...(post.takeaways ? { takeaways: post.takeaways } : {}),
    ...(post.faq ? { faq: post.faq } : {}),
  };
}

function sameShape(source, target) {
  if (typeof source === 'string') return typeof target === 'string' && !!target.trim();
  if (Array.isArray(source)) return Array.isArray(target) && source.length === target.length && source.every((item, i) => sameShape(item, target[i]));
  if (!source || typeof source !== 'object' || !target || typeof target !== 'object') return false;
  const keys = Object.keys(source);
  return keys.length === Object.keys(target).length && keys.every((key) => sameShape(source[key], target[key]));
}

async function translate(locale, post) {
  const source = sourceCopy(post);
  const raw = await openAiChatCompletion({
    messages: [
      { role: 'system', content: `Translate a 30Grow HR blog article from Brazilian Portuguese into ${TARGETS[locale]}. Return a JSON object with exactly the same keys and array lengths as the input. Translate every natural-language field, including title, description, keywords, categoryLabel, intro, every section heading and paragraph, bullets, takeaways and FAQ. Preserve factual meaning, numbers, product capabilities and caveats. Keep 30Grow, 3035Tech, eNPS, LGPD, ATS, LMS, PDI, OKR and Enneagram terminology accurate for the target locale. Use clear, idiomatic professional language. Do not add claims or commentary. Do not translate JSON property names. Do not use a spaced em dash.` },
      { role: 'user', content: JSON.stringify(source) },
    ],
    temperature: 0.1,
    maxTokens: 6500,
    responseFormat: 'json_object',
    timeoutMs: 120000,
  });
  const copy = JSON.parse(extractJsonObject(raw));
  if (!sameShape(source, copy)) throw new Error('translated structure differs from source');
  if (copy.intro === source.intro) throw new Error('article body was not translated');
  return copy;
}

async function main() {
  if (!isOpenAiConfigured() || isOpenAiMock()) throw new Error('A real OPENAI_API_KEY is required');
  if (process.env.OPENAI_TRANSLATE_MODEL) process.env.OPENAI_RUBRIC_MODEL = process.env.OPENAI_TRANSLATE_MODEL;
  mkdirSync(DIR, { recursive: true });
  const posts = listBlogPosts();
  const locales = process.argv.slice(2).filter((locale) => TARGETS[locale]);
  for (const locale of locales.length ? locales : Object.keys(TARGETS)) {
    const file = path.join(DIR, `${locale}.js`);
    let translated = {};
    try { translated = (await import(`${pathToFileURL(file).href}?t=${Date.now()}`)).default; } catch { /* first run */ }
    for (const post of posts) {
      if (translated[post.slug] && sameShape(sourceCopy(post), translated[post.slug])) continue;
      let lastError;
      for (let attempt = 1; attempt <= 3; attempt += 1) {
        try {
          translated[post.slug] = await translate(locale, post);
          lastError = null;
          break;
        } catch (error) {
          lastError = error;
          if (error.code === 'RUBRIC_AI_AUTH') throw error;
        }
      }
      if (lastError) throw new Error(`${locale}/${post.slug}: ${lastError.message}`);
      writeFileSync(file, `// Generated by scripts/i18n-translate-blog.mjs. Review editorial wording before publication.\nexport default ${JSON.stringify(translated, null, 2)};\n`);
      console.log(`${locale}: ${Object.keys(translated).length}/${posts.length} ${post.slug}`);
    }
  }
}

main().catch((error) => { console.error(error.message); process.exitCode = 1; });
